type LegSeed = {
  id: string;
  date: string;
  depart: string;
  arrive: string;
  from: string;
  to: string;
  hours: number;
  fuel: number;
  fees: number;
  handling: number;
  catering?: number;
  posting?: Posting;
};

type TripSeed = {
  id: string;
  aircraftId: string;
  title: string;
  purpose: Purpose;
  requestedBy: string;
  passengers: string[];
  status: ItineraryStatus;
  note: string;
  conditional?: string;
  legs: LegSeed[];
};

function viagem(seed: TripSeed): Itinerary {
  const crew = TRIPULACAO[seed.aircraftId] ?? { commanderId: "paulo" };
  const legs: Leg[] = seed.legs.map((leg) => ({
    id: leg.id,
    date: leg.date,
    depart: leg.depart,
    arrive: leg.arrive,
    fromIcao: leg.from,
    toIcao: leg.to,
    fromCity: AERODROMOS[leg.from] ?? leg.from,
    toCity: AERODROMOS[leg.to] ?? leg.to,
    blockHours: leg.hours,
    fuel: leg.fuel,
    fees: leg.fees,
    handling: leg.handling,
    catering: leg.catering ?? 0,
    commanderId: crew.commanderId,
    copilotId: crew.copilotId,
    posting: leg.posting,
  }));

  return {
    id: seed.id,
    aircraftId: seed.aircraftId,
    title: seed.title,
    purpose: seed.purpose,
    requestedBy: seed.requestedBy,
    passengers: seed.passengers,
    status: seed.status,
    note: seed.note,
    conditional: seed.conditional,
    legs,
  };
}

